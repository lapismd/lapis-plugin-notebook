export async function createDemoNotebooks(app: App): Promise<string> {
  await app.vault.createFolder(DEMO_NOTEBOOK_ROOT);
  await app.vault.createFolder(DEMO_ASSETS_ROOT);

  for (const file of DEMO_NOTEBOOK_FILES) {
    await upsertVaultFile(
      app,
      joinPath(DEMO_NOTEBOOK_ROOT, file.path),
      file.content,
    );
  }

  new Notice(`Wrote notebook demo suite to ${DEMO_NOTEBOOK_ROOT}`);
  return DEMO_NOTEBOOK_ROOT;
}

async function upsertVaultFile(
  app: App,
  path: string,
  content: string,
): Promise<void> {
  const existing = app.vault.getAbstractFileByPath(path);
  if (!existing) {
    await app.vault.create(path, content);
    return;
  }

  if (isVaultFile(existing)) {
    await app.vault.modify(existing, content);
    return;
  }

  throw new Error(`${path} already exists as a folder`);
}

function isVaultFile(value: unknown): value is TFile {
  return (
    typeof value === "object" &&
    value !== null &&
    "extension" in value &&
    "path" in value
  );
}
